# ---------------------------------------------------------------- 数学算式硬校验工具
_EXPR_ALLOWED = re.compile(r"^[\d+\-*/().\s]+$")


def math_expr_value(expr) -> float:
    """安全求值小学四则运算表达式，失败返回 None。

    支持三种形态：
    - 纯算式/纯数字："9+5"、"13"、"10+5=15"（取 = 左边）
    - 过程描述带明确结果："把9凑成10，6还剩5，10+5=15"（取 = 右边结果）
    仅文字过程（如"7要分成2和5"）无明确数值结果 → 返回 None（交由 prompt 约束）。
    × ÷ ＋ － ＝ 全角符号先归一化为半角。
    """
    if not expr:
        return None
    s = str(expr).strip()
    s = (s.replace("×", "*").replace("÷", "/")
          .replace("＋", "+").replace("－", "-")
          .replace("＝", "=").replace("（", "(").replace("）", ")"))
    # 1) 纯算式/纯数字（含 "10+5=15" 取 = 左边）
    e = s.split("=")[0].strip() if "=" in s else s.strip()
    if e and _EXPR_ALLOWED.fullmatch(e):
        try:
            return round(float(eval(e, {"__builtins__": {}}, {})), 6)
        except Exception:
            pass
    # 2) 过程描述：提取「算式 = 数字」的明确结果（取最后一个）
    eq_matches = re.findall(r"\d+\s*[+\-*/]\s*\d+(?:\s*[+\-*/]\s*\d+)*\s*=\s*\d+(?:\.\d+)?", s)
    if eq_matches:
        last = eq_matches[-1]
        val = re.search(r"=\s*(\d+(?:\.\d+)?)\s*$", last)
        if val:
            try:
                return round(float(val.group(1)), 6)
            except Exception:
                return None
    return None


def validate_math_choice(q: dict) -> bool:
    """数学选择题硬校验：可解析出数值的选项之间不允许重复值，且正确答案唯一。

    - 4 个选项都能解析 → 严格校验：恰好 1 个等于答案、且四值互不相同；
    - ≥2 个选项能解析 → 部分校验：可解析选项值不得互相重复（防双正确答案），
      答案选项若可解析，其值不得在其余可解析选项中出现；
    - <2 个选项能解析 → 无法数值验证，放行（交给 prompt 约束）。
    """
    import re as _re
    opts = q.get("options") or []
    if len(opts) != 4:
        return False
    vals = [math_expr_value(o) for o in opts]
    n_valid = sum(1 for v in vals if v is not None)
    if n_valid < 2:
        return True
    # 可解析选项之间不得有重复值
    parsed = [v for v in vals if v is not None]
    if len(set(parsed)) != len(parsed):
        return False
    ans = (q.get("answer") or "").strip()
    if _re.fullmatch(r"[A-Da-d]", ans):
        idx = ord(ans.upper()) - ord("A")
        if idx >= len(vals):
            return False
        correct_val = vals[idx]
    else:
        av = math_expr_value(ans)
        if av is None:
            return True  # 答案本身不可解析时无法验证
        correct_val = av
    if correct_val is None:
        return True
    if n_valid == 4:
        # 全量校验：恰好一个选项等于正确答案
        return sum(1 for v in vals if v == correct_val) == 1
    # 部分校验：答案选项若可解析，其余可解析选项不得等于它
    others = [v for i, v in enumerate(vals) if i != idx and v is not None]
    return correct_val not in others


def normalize_math_numbers(text: str):
    """提取文本中所有数字并排序（用于算式/数字组合去重，交换律等价）。

    例："8+5" 与 "5+8" 都得到 (5, 8)。
    """
    nums = re.findall(r"\d+", text or "")
    if not nums:
        return None
    return tuple(sorted(int(n) for n in nums))


def extract_math_signatures(text: str):
    """数学题去重签名：(算式对集合, 数字元组)。

    - 算式对：题干中所有 "X 运算符 Y" 片段（排序元组集合），过程子算式也计入
    - 数字元组：题干全部数字（排序）
    """
    nums = [int(n) for n in re.findall(r"\d+", text or "")]
    num_tuple = tuple(sorted(nums)) if nums else None
    ops = set()
    for m in re.finditer(r"(\d+)\s*[+\-*/×÷]\s*(\d+)", text or ""):
        ops.add(tuple(sorted((int(m.group(1)), int(m.group(2))))))
    return ops, num_tuple


def math_signatures_conflict(sig1, sig2) -> bool:
    """两道数学题是否判定重复：共享任一算式对、数字组合相同，或
    一题的数字组合与另一题的算式对匹配（应用题 7辆+6辆 ↔ 算式题 7+6）。"""
    ops1, n1 = sig1
    ops2, n2 = sig2
    if ops1 and ops2 and (ops1 & ops2):
        return True
    if n1 and n2 and n1 == n2:
        return True
    # 交叉匹配：应用题数字组合 ⊇ 算式题的某个算式对
    if n1 and ops2 and any(set(t) <= set(n1) for t in ops2):
        return True
    if n2 and ops1 and any(set(t) <= set(n2) for t in ops1):
        return True
    return False
