def stage_of_grade(grade) -> str:
    """按年级推学段：1-6 小学，7-9 初中，10-12 高中，未知默认小学"""
    try:
        g = int(grade or 0)
    except (TypeError, ValueError):
        g = 0
    if g >= 10:
        return "高中"
    if g >= 7:
        return "初中"
    return "小学"


def get_subject_stage_prompt(subject: str = "", grade=None, overrides: dict = None) -> str:
    """按 科目×学段 取出题 prompt = 学段真题段 + 科目基础段。

    降级规则：查不到（科目, 学段）组合时，高中用高中通用段，其他用该科目小学段；
    科目未知用通用基础段。
    overrides：运营后台配置（prompt_rules_service.load_prompt_rule_map），
    按 "base:科目" / "style:科目:学段" 覆盖内置默认；未配置的 scope 用默认。
    """
    s = subject or ""
    subj = next((k for k in ("数学", "语文", "英语") if k in s), "默认")
    stage = stage_of_grade(grade)
    base = SUBJECT_BASES.get(subj, SUBJECT_BASES["默认"])
    style = STAGE_STYLES.get((subj, stage))
    if style is None:
        if stage == "高中":
            style = SENIOR_COMMON_STYLE
        else:
            style = STAGE_STYLES.get((subj, "小学"), "")
    if overrides:
        base = overrides.get(f"base:{subj}", base) or base
        style = overrides.get(f"style:{subj}:{stage}", style) or style
    return (style + "\n\n" + base) if style else base


def get_subject_prompt(subject: str = "") -> str:
    """兼容旧调用：不带年级，默认小学学段"""
    return get_subject_stage_prompt(subject, None)


